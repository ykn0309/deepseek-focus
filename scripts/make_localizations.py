def quote(value: str) -> str:
    return '"' + value.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n') + '"'

root = Path(__file__).resolve().parent.parent
for lang, values in [
    ("en", {k: T[k] for k in T}),
    ("zh-Hans", {k: k for k in T}),
]:
    directory = root / "Resources" / f"{lang}.lproj"
    directory.mkdir(parents=True, exist_ok=True)
    lines = ["/* DeepSeek Focus UI strings */"]
    for key in sorted(values):
        lines.append(f"{quote(key)} = {quote(values[key])};")
    (directory / "Localizable.strings").write_text("\n".join(lines) + "\n", encoding="utf-8")

(root / "Resources" / "en.lproj" / "InfoPlist.strings").write_text(
    '"CFBundleDisplayName" = "DeepSeek Focus";\n"CFBundleName" = "DeepSeek Focus";\n',
    encoding="utf-8",
)
print(f"wrote {len(T)} keys")
